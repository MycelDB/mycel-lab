#!/usr/bin/env python3
"""Generate/check same-space domain and configured-model compatibility cases.

Only definitions are generated. No provider or cluster is contacted.
"""
import argparse
from pathlib import Path
from generateSemanticFaultMatrix import base, definition, event, search

ROOT = Path(__file__).resolve().parents[1]


def phase(name, *events):
    result = {'name': name, 'duration': '1ms', 'events': list(events)}
    if any(e['type'] == 'rolling-restart' for e in events):
        result['outcome'] = {'availability': 'expected-degradation'}
    return result


def restart():
    return [event('rolling-restart', scope='cluster'),
            event('cluster-recovery-wait', timeout='60s', interval='200ms', commandTimeout='3s',
                  sessionInitTimeout='10s', minimumStablePolls=3, reuseEndpointSessions=True)]


def document(name, proof):
    return f'''# {name}

Generated by `scripts/generateSemanticCompatibilityCases.py`. Edit its declared
fixtures and regenerate; generated definitions are not runtime qualification.

## Purpose

{proof}

## What this test proves

Public graph commits, exact semantic scope/route/provenance, negative controls,
and record/generation persistence contribute directly to the run verdict. No
lexical/hybrid/scan fallback, warning, missing diagnostic, or repair reset passes.

## Topology

Three disposable Compose Raft daemons, retained data through rolling restart,
and the local deterministic fake/token-basis embedding connector. No provider
emulator, external credentials, or hosted provider is required. Background semantic
scheduling is disabled; ordinary public maintenance APIs remain available.

```mermaid
flowchart LR
    Lab --> A[myceld-a]
    Lab --> B[myceld-b]
    Lab --> C[myceld-c]
    A <--> B
    B <--> C
    C <--> A
```

## Scenario phases

The adjacent YAML defines five finite phases, including positive baseline,
controlled compatibility/isolation transitions, and retained-restart persistence.
Only migration uses explicit authorized rebuilds, after proving rejection and
advanced generation. Isolation never repairs its indexes to mask leakage.

## Actors

Three endpoint-local semantic controllers provide normal authenticated clients.
A domain peer retains the same principal and space while changing only domain.
Alternate route resources remain owned and tracked for ordinary cleanup.

## Tunable parameters

Immutable v0.21.4 is pinned in manifest and Compose selection. Public operations
have 30-second bounds. Recovery requires three stable health polls within 60
seconds. Domain variants, model listings, and cleanup resource graphs are finite.
Image/fixture changes require fresh evidence and approval, not weakened assertions.

## Evidence and artifacts

Retain acknowledged per-domain graph revisions, exact scope identities, broad
search requests and semantic provenance, migration rejection/generation states,
selected configured IDs and vector shapes, record/configuration captures, endpoint
recovery, final oracle, mandatory cleanup/absence, and redaction verdicts. Payload
checks retain verdicts, not confidential graph content.

## Common failure modes

Changed principal/space masquerading as domain isolation, empty decoy indexes,
rule-filtered queries masquerading as broad isolation, wrong-domain hydration,
non-advancing generation, stale model/vector identity, accepted pre-rebuild search,
replayed post-restart records, and incomplete cleanup all fail closed. Failed
mutations are not automatically resubmitted.

## When to run

Planning only:

```sh
mycel-lab run scenario {name} --dry-run
```

A real run modifies disposable Compose resources and needs explicit fresh
operator approval of the exact clean source/image/artifact identities. Unit tests
and dry-runs are harness evidence, not daemon acceptance or run authorization.
'''


def generated_files():
    files = {}
    name = 'compose-semantic-domain-isolation'
    node = '00000000-0000-4000-8000-000000004670'
    scenario = base(name, 'deterministic-token-basis-v1', 4670)
    del scenario['environment']['options']['providerEmulatorImage']
    def isolation(query, **extra):
        return event('semantic-domain-isolation-assert', peer='secondary', nodeId=node,
                     primaryQuery='axis-0', peerQuery=query, expectPrimaryRevisionFrom='primary-commit',
                     expectPeerRevisionFrom='peer-commit' if query == 'axis-2' else 'peer-update', timeout='30s', **extra)
    scenario['phases'] = [
        phase('index-primary-domain',
              event('semantic-node-create', nodeId=node, labels=['Document'], text='axis-0', captureRevisionAs='primary-commit'),
              event('semantic-rule-create', semantic='deferred'),
              event('semantic-backfill', force=True, limit=1, expectedSelected=1, minimumGenerated=1),
              event('semantic-maintenance-await', timeout='30s', pollInterval='100ms')),
        phase('index-distinct-domain-with-same-principal-space-and-node-id',
              event('semantic-domain-peer-create', name='secondary'),
              event('semantic-node-create', scope='secondary', nodeId=node, labels=['Document'], text='axis-2', captureRevisionAs='peer-commit'),
              event('semantic-rule-create', scope='secondary', semantic='deferred'),
              event('semantic-backfill', scope='secondary', force=True, limit=1, expectedSelected=1, minimumGenerated=1),
              event('semantic-maintenance-await', scope='secondary', timeout='30s', pollInterval='100ms')),
        phase('prove-broad-search-and-hydration-boundaries',
              isolation('axis-2', capturePrimaryRecordAs='primary-record', capturePeerRecordAs='peer-record')),
        phase('peer-update-does-not-replace-primary-record',
              event('semantic-node-update', scope='secondary', nodeId=node, text='axis-3', captureRevisionAs='peer-update'),
              event('semantic-maintenance-await', scope='secondary', timeout='30s', pollInterval='100ms'),
              isolation('axis-3', expectPrimaryRecordFrom='primary-record', capturePeerRecordAs='updated-peer-record')),
        phase('retained-restart-preserves-independent-domain-records',
              *restart(), isolation('axis-3', expectPrimaryRecordFrom='primary-record', expectPeerRecordFrom='updated-peer-record')),
    ]
    directory = f'tests/reliability/scenarios/{name}'
    files[f'{directory}/{name}.yaml'] = definition(scenario)
    files[f'{directory}/{name}.md'] = document(name, 'Prove domain-only isolation with the same authorized principal, the same space, the same node UUID in two distinct normal domains, and positive active indexes in both. Broad searches omit both rule and binding filters; exact configured provenance and hydrated payloads must match their own domain. A peer update and retained restart must preserve the independent primary record.')

    name = 'compose-semantic-model-migration'
    node = '00000000-0000-4000-8000-000000004680'
    scenario = base(name, 'deterministic-token-basis-v1', 4680)
    del scenario['environment']['options']['providerEmulatorImage']
    route = 'model-v2'
    space_a = 'mycel/token-basis-v1/8'
    space_b = 'mycel/migrated-space-v3'
    def current_search(dimensions, vector_space, **extra):
        return search(node, 'axis-0', 'graph-commit', requireConfiguredRoute=True, configuredRoute=route,
                      expectedDimensions=dimensions, expectedVectorSpaceKey=vector_space,
                      expectedPayloadText='axis-0', **extra)
    def fence(previous):
        return [event('semantic-reliability-assert', expectRebuildRequired=True, requireGenerationAfter=previous),
                event('semantic-search-assert', query='axis-0', expectFailureCode='FailedPrecondition')]
    scenario['phases'] = [
        phase('establish-old-configured-model-and-vector-shape',
              event('semantic-node-create', nodeId=node, labels=['Document'], text='axis-0', captureRevisionAs='graph-commit'),
              event('semantic-rule-create', semantic='deferred'),
              event('semantic-backfill', force=True, limit=1, expectedSelected=1, minimumGenerated=1),
              event('semantic-maintenance-await', timeout='30s', pollInterval='100ms'),
              event('semantic-reliability-assert', requireFreshAtLatest=True, captureGenerationAs='baseline-generation'),
              search(node, 'axis-0', 'graph-commit', requireConfiguredRoute=True, expectedDimensions=8,
                     expectedVectorSpaceKey=space_a, captureRecordAs='baseline-record', captureConfigurationHashAs='baseline-config')),
        phase('configured-model-identity-migration-requires-explicit-rebuild',
              event('semantic-route-create', name=route, dimensions=8, vectorSpaceKey=space_a),
              event('semantic-reliability-assert', requireFreshAtLatest=True, expectGenerationFrom='baseline-generation'),
              event('semantic-route-bind', route=route), *fence('baseline-generation'),
              event('semantic-rebuild', backfillLimit=16, maintenanceBatchLimit=64, maxCatchupIterations=64, captureGenerationAs='model-generation'),
              current_search(8, space_a, expectGenerationFrom='model-generation', rejectRecordFrom='baseline-record',
                             rejectConfigurationHashFrom='baseline-config', captureRecordAs='model-record', captureConfigurationHashAs='model-config')),
        phase('dimension-change-alone-invalidates-old-generation',
              event('semantic-model-config-update', route=route, dimensions=16), *fence('model-generation'),
              event('semantic-rebuild', backfillLimit=16, maintenanceBatchLimit=64, maxCatchupIterations=64, captureGenerationAs='dimension-generation'),
              current_search(16, space_a, expectGenerationFrom='dimension-generation', rejectRecordFrom='model-record',
                             rejectConfigurationHashFrom='model-config', captureRecordAs='dimension-record', captureConfigurationHashAs='dimension-config')),
        phase('vector-space-change-alone-invalidates-old-generation',
              event('semantic-model-config-update', route=route, vectorSpaceKey=space_b), *fence('dimension-generation'),
              event('semantic-rebuild', backfillLimit=16, maintenanceBatchLimit=64, maxCatchupIterations=64, captureGenerationAs='space-generation'),
              current_search(16, space_b, expectGenerationFrom='space-generation', rejectRecordFrom='dimension-record',
                             rejectConfigurationHashFrom='dimension-config', captureRecordAs='space-record', captureConfigurationHashAs='space-config')),
        phase('migrated-identity-shape-and-record-survive-retained-restart',
              *restart(), event('semantic-reliability-assert', requireFreshAtLatest=True, expectGenerationFrom='space-generation', expectFreshRevisionFrom='graph-commit'),
              current_search(16, space_b, expectGenerationFrom='space-generation', expectRecordFrom='space-record', expectConfigurationHashFrom='space-config')),
    ]
    directory = f'tests/reliability/scenarios/{name}'
    files[f'{directory}/{name}.yaml'] = definition(scenario)
    files[f'{directory}/{name}.md'] = document(name, 'Migrate to a distinct configured model/profile/endpoint/vector-store route at the same vector shape, then independently change model dimensions and vector-space identity. Unselected route creation must not rotate generation. Each incompatible change must advance generation and reject search until an explicit authorized rebuild. Every rebuilt record must carry the selected route, exact dimensions/vector space, a new configuration/record identity, and the unchanged acknowledged graph revision. Final retained restart must preserve that record.')
    return files


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    failures = []
    for relative, content in generated_files().items():
        path = ROOT / relative
        if args.check:
            if not path.is_file() or path.read_text() != content:
                failures.append(relative)
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content)
    if failures:
        raise SystemExit('generated compatibility case drift: ' + ', '.join(failures))
    print(f'{"Checked" if args.check else "Generated"} {len(generated_files())} compatibility fixture files; no runtime execution')


if __name__ == '__main__':
    main()
